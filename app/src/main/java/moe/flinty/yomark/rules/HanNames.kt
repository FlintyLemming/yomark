package moe.flinty.yomark.rules

/** 认汉字名的几处（姓名字段、身份证人像面、毕业证正文、证件上的汉字名）共用的写法。 */
internal object HanNames {

    /**
     * 少数民族名里不带空格的间隔点：「·」读成的「.」「．」，也常读成「-」「。」（「阿依古丽-买买提」「阿依古丽。买买提」）。
     * 真的间隔点（「·」「•」「・」「‧」）两边还会多出空格，见 [SPACED_DOT]。
     */
    const val DOT = """[.．\-－。]"""

    /** 间隔点本身，两边可有空格。 */
    const val SPACED_DOT = """ ?[·•・‧] ?"""

    /** 带间隔点的名字：每段一到八个汉字，两到四段。 */
    const val DOTTED = """[\u4e00-\u9fa5]{1,8}(?:(?:$SPACED_DOT|$DOT)[\u4e00-\u9fa5]{1,8}){1,3}"""

    /** 间隔点的各种读法，一个字一个字地比时用。 */
    const val DOT_CHARS = "·•・‧.．-－。"

    /** 间隔点的各种读法，正则里的一个字。 */
    const val ANY_DOT = """[·•・‧.．\-－。]"""

    /**
     * 句子里的字，名字里几乎没有：「所有人 都到了」「张三，男，女都可以」。「和」「会」不在里面：和平、会军是名字。
     */
    const val SENTENCE_CHARS = "的了是都也与或在我你他她它们这那吗呢吧啊呀哦嘛哈很没不就还要"
}
